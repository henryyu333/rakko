//go:build darwin

package platform

import "slices"

// ClipboardKind is what one clipboard change should become. Not-ready is
// distinct from skip: the contents are still being published and the caller
// must wait, while a skipped change will never be recorded.
type ClipboardKind int

const (
	ClipboardNotReady ClipboardKind = iota // no type declared yet
	ClipboardSkip                          // private, files, or nothing usable
	ClipboardText
	ClipboardImage
)

// privateClipTypes are the markers password managers and similar sources
// set to ask clipboard history tools not to record a copy.
var privateClipTypes = []string{
	"org.nspasteboard.ConcealedType",
	"org.nspasteboard.TransientType",
	"org.nspasteboard.AutoGeneratedType",
	"com.agilebits.onepassword",
	"de.petermaurer.TransientPasteboardType",
	"net.antelle.keeweb",
}

var (
	clipTextTypes  = []string{"public.utf8-plain-text", "public.utf16-plain-text", "NSStringPboardType"}
	clipImageTypes = []string{"public.png", "public.tiff", "NSTIFFPboardType"}
	clipFileTypes  = []string{"public.file-url", "NSFilenamesPboardType"}
)

// ClassifyClipboard decides what a clipboard change should add, from the
// pasteboard's declared types in the source's order of preference. No types
// at all means the change has not been published yet. File copies are
// skipped: their image is only the file icon and their text only the file
// name. When both text and an image are offered (Office, Numbers, web
// pages), the representation the source lists first wins, so a spreadsheet
// copy is kept as text and a copied picture as an image.
func ClassifyClipboard(types []string) ClipboardKind {
	if len(types) == 0 {
		return ClipboardNotReady
	}
	for _, t := range types {
		if slices.Contains(privateClipTypes, t) {
			return ClipboardSkip
		}
	}
	for _, t := range types {
		if slices.Contains(clipFileTypes, t) {
			return ClipboardSkip
		}
	}
	for _, t := range types {
		switch {
		case slices.Contains(clipTextTypes, t):
			return ClipboardText
		case slices.Contains(clipImageTypes, t):
			return ClipboardImage
		}
	}
	return ClipboardSkip
}

// DragHasFiles reports whether the drag declares whole files.
func DragHasFiles(types []string) bool {
	for _, t := range types {
		if t == "public.file-url" || t == "NSFilenamesPboardType" || t == "com.apple.finder.node" {
			return true
		}
	}
	return false
}

// DragHasFilePromise reports whether the drag promises files it will write
// on drop rather than carrying them.
func DragHasFilePromise(types []string) bool {
	for _, t := range types {
		switch t {
		case "com.apple.NSFilePromiseItemMetaData", "com.apple.pasteboard.promised-file-url", "public.file-promise":
			return true
		}
	}
	return false
}

// DragHasImages reports whether the drag carries image data.
func DragHasImages(types []string) bool {
	for _, t := range types {
		if slices.Contains(clipImageTypes, t) ||
			slices.Contains([]string{"public.jpeg", "public.heic", "public.webp", "public.image"}, t) {
			return true
		}
	}
	return false
}

// DragMayCarryFiles reports whether a drag with these declared types may
// wake the shake-to-summon basket and the pin strips: anything carrying
// files, promised files or image data. macOS always knows the types, so
// the answer is exactly that test.
func DragMayCarryFiles(types []string) bool {
	return DragHasFiles(types) || DragHasFilePromise(types) || DragHasImages(types)
}
